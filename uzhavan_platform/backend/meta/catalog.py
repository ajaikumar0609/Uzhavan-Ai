@lru_cache(maxsize=1)
def _district_doc() -> dict[str, Any]:
    return json.loads(_DATA.read_text(encoding="utf-8"))


def districts() -> list[dict[str, Any]]:
    return [
        {"id": d["id"], "name": d["name"], "lat": d["lat"], "lon": d["lon"]}
        for d in _district_doc()["districts"]
    ]


def district_source() -> dict[str, str]:
    return _district_doc()["source"]


@lru_cache(maxsize=1)
def _district_index() -> dict[str, dict[str, Any]]:
    return {d["id"]: d for d in districts()}


def get_district(district_id: str) -> dict[str, Any] | None:
    return _district_index().get(district_id)


def _ids(items: list[dict[str, Any]]) -> set[str]:
    return {i["id"] for i in items}


CROP_IDS = _ids(CROPS)
CROP_STAGE_IDS = _ids(CROP_STAGES)
