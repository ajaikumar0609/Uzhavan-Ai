def _norm_name(name: str) -> str:
    return "".join(ch for ch in name.lower() if ch.isalpha())


@lru_cache(maxsize=1)
def _district_name_index() -> dict[str, str]:
    idx = {_norm_name(d["name"]["en"]): d["id"] for d in districts()}
    idx.update({_norm_name(d["id"]): d["id"] for d in districts()})
    idx.update(_DISTRICT_ALIASES)
    return idx


def district_id_from_name(name: str | None) -> str | None:
    """Map a district spelling from project data to a meta district id; None if unknown."""
    if not name:
        return None
    return _district_name_index().get(_norm_name(name))
